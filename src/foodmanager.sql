-- ============================================
-- 데이터베이스 생성
-- ============================================

DROP DATABASE IF EXISTS foodmanager;

CREATE DATABASE foodmanager;

USE foodmanager;


-- ============================================
-- 1. 카테고리 테이블
-- Category
-- ============================================

CREATE TABLE category (

    cno     INT AUTO_INCREMENT,       -- 카테고리 번호
    cname   VARCHAR(15) NOT NULL,     -- 카테고리명

    CONSTRAINT PRIMARY KEY (cno),
    CONSTRAINT UNIQUE (cname)

);


-- ============================================
-- 2. 상품 테이블
-- Product
-- ============================================

CREATE TABLE product (

    pno       INT AUTO_INCREMENT,     -- 개별 상품 번호
    pname     VARCHAR(50) NOT NULL,   -- 상품명
    pprice    INT NOT NULL,           -- 가격
    pstatus   BOOLEAN NOT NULL DEFAULT 1, -- 판매 여부
    cno       INT NOT NULL,           -- 카테고리 번호(FK)

    CONSTRAINT PRIMARY KEY (pno),

    CONSTRAINT FK_product_category
        FOREIGN KEY (cno)
        REFERENCES category(cno)

);


-- ============================================
-- 3. 상품 관리 테이블
-- Management
-- ============================================

CREATE TABLE management (

    mno         INT AUTO_INCREMENT,   -- 유통 식별 번호
    mdate       DATE NOT NULL,        -- 유통기한
    pno         INT NOT NULL,         -- 개별 상품 번호(FK)
    mstatus     VARCHAR(30) NOT NULL CHECK (mstatus IN ('판매중/입고', '판매', '폐기')), -- 상태
    in_date     DATE NOT NULL,        -- 등록날짜(입고날짜)
    out_date    DATE,                 -- 판매날짜(폐기날짜)

    CONSTRAINT PRIMARY KEY (mno),

    CONSTRAINT FK_management_product
        FOREIGN KEY (pno)
        REFERENCES product(pno)

);

SELECT pname, COUNT(pname) AS Inventory FROM management mm JOIN product pd ON mm.pno = pd.pno WHERE mstatus = "판매중/입고" GROUP BY pname;
